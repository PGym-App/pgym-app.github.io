// PGym Offline-Cache. Bei jeder Änderung an der App die Versionsnummer erhöhen.
const CACHE = 'pgym-v26';
const FILES = ['./', 'index.html', 'manifest.webmanifest', 'icon.svg', 'icon-192.png', 'icon-512.png', 'apple-touch-icon.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
// Erst Netz (damit Updates ankommen), ohne Empfang aus dem Cache.
// cache: 'no-cache' fragt GitHub jedes Mal, ob es Neues gibt (sonst bis zu 10 Minuten alter Stand).
self.addEventListener('fetch', e => {
  // Nur die App selbst cachen, nie Anfragen an GitHub (Sicherung)
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(e.request, { cache: 'no-cache' })
      .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); return res; })
      .catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || caches.match('index.html')))
  );
});
